fig, axes = plt.subplots(2, 2, figsize=(12, 8))
for ax, feature in zip(axes.flat, selected_features):
    sns.histplot(data=train_eda, x=feature, hue="diagnosis",
                 hue_order=[0, 1], bins=25, stat="density",
                 common_norm=False, kde=True,
                 palette={0: "#4C78A8", 1: "#E45756"},
                 alpha=0.35, ax=ax)
    ax.set_title(feature.replace("_", " ").title())
fig.suptitle("Training Feature Distributions by Diagnosis")
save_figure(output_dir / "03_training_feature_distributions.png")

plt.figure(figsize=(14, 10))
sns.heatmap(X_train.corr(), cmap="coolwarm", center=0,
            vmin=-1, vmax=1, linewidths=0.2)
plt.title("Feature Correlations in the Training Set")
save_figure(output_dir / "04_training_correlation_heatmap.png")

"""## Stage 1 (continued): Important features

We used Mutual Information on the training set to see which features are most related to the diagnosis.
"""

# Mutual information is calculated on the training data only.
mi = mutual_info_classif(X_train, y_train, random_state=RANDOM_STATE)
feature_importance = pd.DataFrame({"Feature": X_train.columns, "MI Score": mi})
feature_importance = feature_importance.sort_values("MI Score", ascending=False)
feature_importance.to_csv(tables_dir / "mutual_information.csv", index=False)
plt.figure(figsize=(9, 6))
sns.barplot(data=feature_importance.head(10), x="MI Score", y="Feature",
            color="steelblue")
