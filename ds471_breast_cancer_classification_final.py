"""## Stage 1 (continued): Encoding, feature engineering and scaling

- **Encoding:** all 30 features are numbers, so only the target needed encoding (B = 0, M = 1).
- **Feature engineering:** we did not create new features because the dataset already has detailed measurements of the cell nuclei.
- **Feature selection:** we kept all 30 features. Mutual Information looks at each feature alone, so it does not tell us which group of features works best together.
- **Correlated features:** radius, perimeter and area are strongly correlated. Logistic Regression and the neural network use L2 regularization, and Random Forest is not affected much by this.
- **Scaling:** we used StandardScaler for Logistic Regression, SVM and the Neural Network because they are sensitive to the scale of the features. We put it inside a Pipeline so it is fitted only on training data. Random Forest does not need scaling.
- **Outliers:** kept, as explained above

## Stage 3: Choosing the models

We chose Logistic Regression (simple linear baseline), SVM with an RBF kernel (can learn non-linear boundaries), Random Forest (ensemble of trees), and a Neural Network (MLP, one hidden layer with 32 ReLU neurons), which is required by the project.
"""

# Stage 3: define the required neural network and three traditional models.
models = {
    "Logistic Regression": Pipeline([
        ("scaler", StandardScaler()),
        ("model", LogisticRegression(max_iter=2000, random_state=RANDOM_STATE)),
    ]),
    "Support Vector Machine": Pipeline([
        ("scaler", StandardScaler()),
        ("model", SVC(kernel="rbf", probability=True, random_state=RANDOM_STATE)),
    ]),
    "Random Forest": RandomForestClassifier(random_state=RANDOM_STATE),
    "Neural Network": Pipeline([
        ("scaler", StandardScaler()),
        ("model", MLPClassifier(
            hidden_layer_sizes=(32,), activation="relu",
            max_iter=1000, random_state=RANDOM_STATE)),
    ]),
}

"""## Stage 4: Baseline training and validation

First we train all four models with simple settings and compare training and validation scores to see if there is overfitting.
"""

# Stage 4: baseline results on training and validation sets.
baseline_rows = []
for name, model in models.items():
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        model.fit(X_train, y_train)
    train_pred, train_score = evaluate_model(model, X_train, y_train)
    val_pred, val_score = evaluate_model(model, X_val, y_val)
    baseline_rows.append({
        "Model": name,
        "Train Accuracy": accuracy_score(y_train, train_pred),
        "Validation Accuracy": accuracy_score(y_val, val_pred),
        "Train F1": f1_score(y_train, train_pred, zero_division=0),
        "Validation F1": f1_score(y_val, val_pred, zero_division=0),
        "Validation Malignant Recall": recall_score(y_val, val_pred, zero_division=0),
        "Validation ROC-AUC": roc_auc_score(y_val, val_score),
    })
baseline_results = pd.DataFrame(baseline_rows)
baseline_results.to_csv(tables_dir / "baseline_validation_results.csv", index=False)
print("\nBaseline performance:")
print(baseline_results.round(4).to_string(index=False))

"""## Stage 4: Hyperparameter tuning

We used GridSearchCV with 5-fold stratified cross-validation on the training set only. We used F1-score to choose the best parameters because the classes are not perfectly balanced and missing a malignant case is serious.
"""

# Hyperparameter search runs only on training data; scaling is inside pipelines.
param_grids = {
    "Logistic Regression": {
        "model__C": [0.01, 0.1, 1, 10, 100],
        "model__solver": ["lbfgs", "liblinear"],
    },
    "Support Vector Machine": {
        "model__C": [0.1, 1, 10, 100],
        "model__gamma": ["scale", "auto", 0.01, 0.001],
    },
    "Random Forest": {
        "n_estimators": [100, 200],
        "max_depth": [None, 5, 10, 15],
        "min_samples_split": [2, 5, 10],
        "min_samples_leaf": [1, 2, 4],
    },
    "Neural Network": {
        "model__hidden_layer_sizes": [(32,), (64,), (32, 16), (64, 32)],
        "model__alpha": [0.0001, 0.001, 0.01, 0.1],
        "model__learning_rate_init": [0.001, 0.01],
    },
}
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
tuned_models = {}
tuning_rows = []
for name, model in models.items():
    print(f"\nTuning {name}...")
    search = GridSearchCV(
        estimator=clone(model),
        param_grid=param_grids[name],
        scoring="f1",
        cv=cv,
        n_jobs=-1,
        refit=True,
        return_train_score=False,
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        search.fit(X_train, y_train)
    tuned_models[name] = search.best_estimator_
    tuning_rows.append({
        "Model": name,
        "Best CV F1": search.best_score_,
        "Best Parameters": str(search.best_params_),
    })
tuning_results = pd.DataFrame(tuning_rows)
tuning_results.to_csv(tables_dir / "hyperparameter_search.csv", index=False)
print("\nBest hyperparameters from training-set cross-validation:")
print(tuning_results.to_string(index=False))

"""### Tuned models on training vs. validation"""

tuned_validation_rows = []
for name, model in tuned_models.items():
    train_pred, _ = evaluate_model(model, X_train, y_train)
    val_pred, val_score = evaluate_model(model, X_val, y_val)
    tuned_validation_rows.append({
        "Model": name,
        "Train Accuracy": accuracy_score(y_train, train_pred),
        "Validation Accuracy": accuracy_score(y_val, val_pred),
        "Train F1": f1_score(y_train, train_pred, zero_division=0),
        "Validation F1": f1_score(y_val, val_pred, zero_division=0),
        "Validation Malignant Recall": recall_score(y_val, val_pred, zero_division=0),
        "Validation ROC-AUC": roc_auc_score(y_val, val_score),
    })
tuned_validation = pd.DataFrame(tuned_validation_rows)
tuned_validation.to_csv(tables_dir / "tuned_validation_results.csv", index=False)
print("\nTuned model validation results:")
print(tuned_validation.round(4).to_string(index=False))

"""### Neural Network curves before fixing overfitting

These curves show the loss and accuracy of the tuned network at each epoch. The training loss keeps going down, but the validation loss starts to go up after about epoch 11, which means the network is overfitting.
"""

# Plot learning curves for the selected initial MLP configuration.
scaler = StandardScaler().fit(X_train)
X_train_scaled = scaler.transform(X_train)
X_val_scaled = scaler.transform(X_val)
initial_mlp = MLPClassifier(
    hidden_layer_sizes=(64,), activation="relu", solver="adam",
    alpha=0.0001, learning_rate_init=0.01, max_iter=1,
    random_state=RANDOM_STATE,
)
initial_history = {"epoch": [], "train_loss": [], "val_loss": [],
                   "train_accuracy": [], "val_accuracy": []}
for epoch in range(1, 101):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        if epoch == 1:
            initial_mlp.partial_fit(X_train_scaled, y_train, classes=np.array([0, 1]))
        else:
            initial_mlp.partial_fit(X_train_scaled, y_train)
    train_prob = initial_mlp.predict_proba(X_train_scaled)
    val_prob = initial_mlp.predict_proba(X_val_scaled)
    initial_history["epoch"].append(epoch)
    initial_history["train_loss"].append(log_loss(y_train, train_prob, labels=[0, 1]))
    initial_history["val_loss"].append(log_loss(y_val, val_prob, labels=[0, 1]))
    initial_history["train_accuracy"].append(
        accuracy_score(y_train, initial_mlp.predict(X_train_scaled))
    )
    initial_history["val_accuracy"].append(
        accuracy_score(y_val, initial_mlp.predict(X_val_scaled))
    )
pd.DataFrame(initial_history).to_csv(tables_dir / "initial_mlp_history.csv", index=False)
fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
axes[0].plot(initial_history["epoch"], initial_history["train_loss"], label="Training")
axes[0].plot(initial_history["epoch"], initial_history["val_loss"], label="Validation")
axes[0].set(title="Initial MLP Loss", xlabel="Epoch", ylabel="Log Loss")
axes[0].legend()
axes[1].plot(initial_history["epoch"], initial_history["train_accuracy"], label="Training")
axes[1].plot(initial_history["epoch"], initial_history["val_accuracy"], label="Validation")
axes[1].set(title="Initial MLP Accuracy", xlabel="Epoch", ylabel="Accuracy")
axes[1].legend()
fig.suptitle("Initial Neural Network Training and Validation Curves")
save_figure(output_dir / "06_initial_mlp_curves.png")

"""### Neural Network after regularization and early stopping

To reduce overfitting we used a stronger L2 penalty (alpha = 1.0), a smaller network (32 neurons), a lower learning rate (0.003), and early stopping based on the validation loss. We keep the weights from the epoch with the lowest validation loss.
"""

# Train a smaller, more strongly regularized MLP and apply early stopping
# using validation log loss. The test set is not used in this process.
final_mlp = MLPClassifier(
    hidden_layer_sizes=(32,), activation="relu", solver="adam",
    alpha=1.0, learning_rate_init=0.003, max_iter=1,
    random_state=RANDOM_STATE,
)
regularized_history = {"epoch": [], "train_loss": [], "val_loss": [],
                       "train_accuracy": [], "val_accuracy": []}
best_loss = np.inf
best_epoch = 0
best_model = None
patience = 15
epochs_without_improvement = 0
for epoch in range(1, 101):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        if epoch == 1:
            final_mlp.partial_fit(X_train_scaled, y_train, classes=np.array([0, 1]))
        else:
            final_mlp.partial_fit(X_train_scaled, y_train)
    train_prob = final_mlp.predict_proba(X_train_scaled)
    val_prob = final_mlp.predict_proba(X_val_scaled)
    train_loss = log_loss(y_train, train_prob, labels=[0, 1])
    val_loss = log_loss(y_val, val_prob, labels=[0, 1])
    regularized_history["epoch"].append(epoch)
    regularized_history["train_loss"].append(train_loss)
    regularized_history["val_loss"].append(val_loss)
    regularized_history["train_accuracy"].append(
        accuracy_score(y_train, final_mlp.predict(X_train_scaled))
    )
    regularized_history["val_accuracy"].append(
        accuracy_score(y_val, final_mlp.predict(X_val_scaled))
    )
    if val_loss < best_loss:
        best_loss = val_loss
        best_epoch = epoch
        best_model = deepcopy(final_mlp)
        epochs_without_improvement = 0
    else:
        epochs_without_improvement += 1
    if epochs_without_improvement >= patience:
        break
pd.DataFrame(regularized_history).to_csv(
    tables_dir / "regularized_mlp_history.csv", index=False
)
print(f"\nRegularized MLP best epoch: {best_epoch}")
print(f"Early stopping occurred at epoch: {regularized_history['epoch'][-1]}")

fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
axes[0].plot(regularized_history["epoch"], regularized_history["train_loss"], label="Training")
axes[0].plot(regularized_history["epoch"], regularized_history["val_loss"], label="Validation")
axes[0].axvline(best_epoch, color="black", linestyle="--", label=f"Best epoch {best_epoch}")
axes[0].set(title="Regularized MLP Loss", xlabel="Epoch", ylabel="Log Loss")
axes[0].legend()
axes[1].plot(regularized_history["epoch"], regularized_history["train_accuracy"], label="Training")
axes[1].plot(regularized_history["epoch"], regularized_history["val_accuracy"], label="Validation")
axes[1].axvline(best_epoch, color="black", linestyle="--", label=f"Best epoch {best_epoch}")
axes[1].set(title="Regularized MLP Accuracy", xlabel="Epoch", ylabel="Accuracy")
axes[1].legend()
fig.suptitle("Regularized Neural Network Training and Validation Curves")
save_figure(output_dir / "07_regularized_mlp_curves.png")

"""### Final models and validation results

The three traditional models use their best cross-validation settings, and the neural network is the regularized version. We compare them on the validation set before touching the test set.
"""

# Select among models using validation performance, not test results.
# The regularized MLP replaces the grid-searched MLP after validation-based
# overfitting analysis; the other three models retain their best CV models.
final_models = {
    "Logistic Regression": tuned_models["Logistic Regression"],
    "Support Vector Machine": tuned_models["Support Vector Machine"],
    "Random Forest": tuned_models["Random Forest"],
    "Neural Network (Regularized MLP)": ScaledMLP(scaler, best_model),
}
# The scaler and MLP are already fitted on training data. The adapter keeps
# the best early-stopping checkpoint without fitting it a second time.

final_validation_rows = []
for name, model in final_models.items():
    val_pred, val_score = evaluate_model(model, X_val, y_val)
    final_validation_rows.append({
        "Model": name,
        "Validation Accuracy": accuracy_score(y_val, val_pred),
        "Validation Precision": precision_score(y_val, val_pred, zero_division=0),
        "Validation Malignant Recall": recall_score(y_val, val_pred, zero_division=0),
        "Validation F1": f1_score(y_val, val_pred, zero_division=0),
        "Validation ROC-AUC": roc_auc_score(y_val, val_score),
    })
final_validation = pd.DataFrame(final_validation_rows)
final_validation.to_csv(tables_dir / "final_validation_results.csv", index=False)
print("\nFinal model validation results (used for model selection):")
print(final_validation.round(4).to_string(index=False))

"""## Stage 5: Final evaluation on the test set

Now we test each final model once on the test set and report accuracy, precision, recall, F1-score, ROC-AUC and the confusion matrix counts.
"""

# Stage 5: evaluate the fixed model configurations on the test set.
test_rows = []
test_predictions = {}
test_scores = {}
for name, model in final_models.items():
    predictions, scores = evaluate_model(model, X_test, y_test)
    test_predictions[name] = predictions
    test_scores[name] = scores
    test_rows.append(metric_row(name, y_test, predictions, scores))
test_results = pd.DataFrame(test_rows).sort_values(
    ["F1-Score", "Recall", "ROC-AUC"], ascending=False
)
test_results.to_csv(tables_dir / "final_test_results.csv", index=False)
print("\nFinal test results (test set used only after model configurations were fixed):")
print(test_results.round(4).to_string(index=False))

"""### Confusion matrices, ROC curves and metric comparison"""

# Confusion matrices for all final models.
fig, axes = plt.subplots(2, 2, figsize=(10, 8))
